test_ldbrx_1:
  #_ MEMORY_IN 10001000 01 02 03 04 05 06 07 08
  #_ REGISTER_IN r4 0x10000000
  #_ REGISTER_IN r5 0x00001000
  ldbrx r3, r4, r5
  blr
  #_ REGISTER_OUT r3 0x0807060504030201
  #_ REGISTER_OUT r4 0x10000000
  #_ REGISTER_OUT r5 0x00001000

